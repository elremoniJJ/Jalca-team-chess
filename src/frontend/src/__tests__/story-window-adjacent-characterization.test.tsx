/**
 * Characterization of the game page's EXISTING window wiring and stack order,
 * taken BEFORE the collapsible Story window replaces the temporary Internet
 * Identity window at the bottom of the game page.
 *
 * The request intentionally:
 *   1. REMOVES the temporary Internet Identity window from the game page and
 *      reuses its slot for the Story window;
 *   2. changes the Layout window stack order (the `internetIdentity` slot goes
 *      away and a `story` slot is added below Prediction Bet);
 *   3. changes the Story backend store from a single text field to a sectioned
 *      model.
 *
 * Those three things are intentional, so this file deliberately does NOT
 * assert the presence of the Internet Identity slot, does NOT assert the
 * absence of a Story slot, and does NOT freeze the exact tail of the stack.
 * What it protects is the behavior ADJACENT to the change that must survive
 * it — the existing game-page windows and their fixed relative order:
 *
 *   - the route still passes every existing window slot to Layout
 *     (voting, status, board, wallet, players, captured, moves,
 *     predictionBet);
 *   - the Prediction Bet slot still carries the real PredictionBetWindow.
 *
 * The fixed relative order of the existing windows (including Prediction Bet
 * as the last of them) is protected by
 * layout-window-stack-order-characterization.test.tsx, which renders the real
 * Layout directly.
 *
 * The route is driven through mocked hooks (no real actor, no polling), and
 * Layout is stubbed to capture the `windows` object it receives. The real
 * window components are covered by their own focused test files.
 */

