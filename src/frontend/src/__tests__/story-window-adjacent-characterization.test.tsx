import { Route as gameRoute } from "@/routes/game";

const GameRouteComponent = gameRoute.options.component!;

function renderRoute() {
  const queryClient = new QueryClient({
    defaultOptions: { queries: { retry: false } },
  });
  return render(
    <QueryClientProvider client={queryClient}>
      <GameRouteComponent />
    </QueryClientProvider>,
  );
}

describe("GameRoute existing window wiring survives the Story window addition", () => {
  afterEach(() => {
    cleanup();
    window.localStorage.clear();
    capturedWindows.current = null;
  });

  it("still passes every existing window slot to Layout", () => {
    renderRoute();

    const windows = capturedWindows.current;
    expect(windows).not.toBeNull();
    for (const key of [
      "voting",
      "status",
      "board",
      "wallet",
      "players",
      "captured",
      "moves",
      "predictionBet",
    ]) {
      expect(windows).toHaveProperty(key);
      expect(windows?.[key]).toBeTruthy();
    }
  });

  it("still wires the Prediction Bet slot to the real PredictionBetWindow", () => {
    renderRoute();

    const predictionBet = capturedWindows.current?.predictionBet as
      | { type?: { name?: string } }
      | undefined;
    expect(predictionBet).toBeTruthy();
    // The slot carries a React element whose component is PredictionBetWindow.
    expect(predictionBet?.type?.name).toBe("PredictionBetWindow");
  });
});
